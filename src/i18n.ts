export function detectInitialLanguage(): string {
  try {
    const params = new URLSearchParams(window.location.search);
    const urlLang = (params.get('lang') || '').trim().toLowerCase();
    if (urlLang && LANGUAGES[urlLang]) {
      localStorage.setItem('bd_collection_lang', urlLang);
      localStorage.setItem('bd_collection_lang_manual', '1');
      return urlLang;
    }
  } catch {}

  const saved = localStorage.getItem('bd_collection_lang');
  if (saved && LANGUAGES[saved]) return saved;

  try {
    const tgLang = (window as any).Telegram?.WebApp?.initDataUnsafe?.user?.language_code;
    if (typeof tgLang === 'string' && tgLang.trim()) {
      const cleanTgLang = tgLang.split('-')[0].toLowerCase();
      if (LANGUAGES[cleanTgLang]) {
        return cleanTgLang;
      }
    }
  } catch {}

  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone;
    if (tz && TIMEZONE_TO_LANG[tz] && LANGUAGES[TIMEZONE_TO_LANG[tz]]) {
      return TIMEZONE_TO_LANG[tz];
    }
  } catch {}

  const navLang = (navigator.language || 'en').split('-')[0].toLowerCase();
  if (LANGUAGES[navLang]) return navLang;

  return 'bn';
}

export async function detectCountryLanguageFromIP(): Promise<string | null> {
  try {
    const res = await fetch('https://ipapi.co/json/', { signal: AbortSignal.timeout(3500) });
    if (!res.ok) return null;
    const data = await res.json();
    const country = String(data.country_code || '').toUpperCase();
    if (country && COUNTRY_TO_LANG[country] && LANGUAGES[COUNTRY_TO_LANG[country]]) {
      return COUNTRY_TO_LANG[country];
    }
  } catch {}
  return null;
}
